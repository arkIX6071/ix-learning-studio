#!/usr/bin/env python3
"""In-memory browser QA with simulated touch; no external publication."""
from __future__ import annotations
import json, math, pathlib
from playwright.sync_api import sync_playwright
ROOT = pathlib.Path(__file__).resolve().parents[1]
results=[]
def check(ok, name, detail=''):
    results.append({'name':name,'pass':bool(ok),'detail':str(detail)})
    if not ok: raise AssertionError(f'{name}: {detail}')
with sync_playwright() as pw:
    browser=pw.chromium.launch(headless=True, executable_path='/usr/bin/chromium', args=['--no-sandbox'])
    for label,viewport,touch in [('desktop',{'width':1280,'height':800},False),('touch',{'width':390,'height':844},True)]:
        ctx=browser.new_context(viewport=viewport,has_touch=touch,is_mobile=touch)
        p=ctx.new_page();errors=[];p.on('pageerror', lambda e:errors.append(str(e)))
        p.set_content((ROOT/'index.html').read_text(encoding='utf-8'), wait_until='domcontentloaded')
        check(p.locator('.lesson').count()==2,f'{label}: 2 lessons')
        check(p.locator('.lesson:visible').count()==2,f'{label}: both lessons visible')
        p.locator('#search').fill('GNSS')
        check(p.locator('.lesson:visible').count()==1,f'{label}: library search filter')
        p.locator('#search').fill('no-such-topic')
        check(p.locator('.lesson:visible').count()==0 and p.locator('#no-results').is_visible(),f'{label}: no results feedback')
        p.locator('#search').fill('')
        check(p.locator('.lesson:visible').count()==2,f'{label}: clearing search resets')
        check(p.evaluate('document.documentElement.scrollWidth <= innerWidth+2'),f'{label}: library no horizontal scroll')
        p.set_content((ROOT/'lessons'/'gnss-epoch'/'index.html').read_text(encoding='utf-8'),wait_until='domcontentloaded')
        check('JavaScript ทำงาน' in p.locator('#js-status').inner_text(),f'{label}: GNSS script runs')
        check(p.locator('#pe').inner_text()=='100.06318',f'{label}: GNSS numerical anchor',p.locator('#pe').inner_text())
        check(abs(float(p.locator('#sigma').inner_text()) - math.hypot(5,4.86))<0.002,f'{label}: GNSS uncertainty')
        old_end=p.locator('#end').get_attribute('cx')
        p.locator('#epoch').evaluate("el=>{el.value='2021.93';el.dispatchEvent(new Event('input',{bubbles:true}))}")
        check(p.locator('#pe').inner_text()=='100.00000',f'{label}: GNSS slider input updates number')
        check(p.locator('#end').get_attribute('cx')!=old_end,f'{label}: GNSS slider updates graphic')
        p.locator('#epoch-num').fill('2028')
        check(abs(float(p.locator('#pe').inner_text())-100.07891)<0.00002,f'{label}: GNSS numeric field')
        p.locator('button[data-target="epoch"][data-dir="1"]').click()
        check(float(p.locator('#epoch').input_value())>2028,f'{label}: GNSS plus button')
        p.locator('#reset').click()
        check(p.locator('#pe').inner_text()=='100.06318',f'{label}: GNSS reset')
        check(not errors,f'{label}: GNSS JS errors',errors)
        check(p.evaluate('document.documentElement.scrollWidth <= innerWidth+2'),f'{label}: GNSS no horizontal scroll')
        p.set_content((ROOT/'lessons'/'newtons-cooling'/'index.html').read_text(encoding='utf-8'),wait_until='domcontentloaded')
        check('JavaScript ทำงาน' in p.locator('#js-status').inner_text(),f'{label}: cooling script runs')
        expected=25+65*math.exp(-.06*15)
        check(abs(float(p.locator('#temperature').inner_text().split()[0])-expected)<0.01,f'{label}: cooling analytic baseline',expected)
        initial_path=p.locator('#curve').get_attribute('d')
        p.locator('#minutes').evaluate("el=>{el.value='0';el.dispatchEvent(new Event('input',{bubbles:true}))}")
        check(p.locator('#temperature').inner_text()=='90.00 °C',f'{label}: cooling at t0')
        check(p.locator('#cursor').get_attribute('x1')=='62',f'{label}: cooling cursor updated')
        p.locator('#k-number').fill('0.1')
        check(abs(float(p.locator('#k').input_value())-.1)<1e-9,f'{label}: cooling numeric field')
        p.locator('#minutes').evaluate("el=>{el.value='15';el.dispatchEvent(new Event('input',{bubbles:true}))}")
        check(float(p.locator('#temperature').inner_text().split()[0])<expected,f'{label}: larger k cools faster')
        check(initial_path!=p.locator('#curve').get_attribute('d'),f'{label}: cooling plot updated')
        p.locator('button[data-id="minutes"][data-delta="1"]').click()
        check(p.locator('#minutes').input_value()=='16',f'{label}: cooling plus button')
        p.locator('#reset').click()
        check(abs(float(p.locator('#temperature').inner_text().split()[0])-expected)<0.01,f'{label}: cooling reset')
        p.locator('input[name="q1"][value="b"]').check();p.locator('input[name="q2"][value="a"]').check();p.locator('input[name="q3"][value="c"]').check();p.locator('#check').click()
        check('PASS' in p.locator('#grade').inner_text(),f'{label}: mastery gate')
        check(not errors,f'{label}: cooling JS errors',errors)
        check(p.evaluate('document.documentElement.scrollWidth <= innerWidth+2'),f'{label}: cooling no horizontal scroll')
        if label=='touch':p.screenshot(path=str(ROOT/'tests'/'preview_mobile.png'),full_page=True)
        ctx.close()
    browser.close()
report={'test_date':'2026-10-15','mode':'Chromium DOM set_content + touch simulation (HTTP navigation blocked in runtime)','actual_ipad_tested':False,'cases':len(results),'passed':sum(v['pass'] for v in results),'results':results}
(ROOT/'tests'/'results.json').write_text(json.dumps(report,ensure_ascii=False,indent=2),encoding='utf-8')
print(json.dumps({'passed':report['passed'],'total':report['cases'],'failures':[i for i in results if not i['pass']]},ensure_ascii=False))
